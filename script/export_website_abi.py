#!/usr/bin/env python3
"""Export ABIs/selectors from the configured Foundry build; --check is offline."""
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent


def export(contract, source, target, variable):
    artifact = json.loads((ROOT / f"out/{source}/{contract}.json").read_text())
    abi = artifact["abi"]
    canonical = json.dumps(abi, sort_keys=True, separators=(",", ":"))
    data = {"contract": contract, "design": "block-random-v1", "abi": abi,
            "abiSha256": hashlib.sha256(canonical.encode()).hexdigest(),
            "selectors": artifact["methodIdentifiers"]}
    result = "// Generated by script/export_website_abi.py from forge build. Not a deployed-contract approval.\n"
    result += f"globalThis.{variable} = " + json.dumps(data, indent=2) + ";\n"
    path = ROOT / target
    if "--check" in sys.argv:
        if path.read_text() != result:
            raise SystemExit(f"Stale generated ABI: {target}")
    else:
        path.write_text(result)


export("BMCIlluminatiPass", "BMCIlluminatiPass.sol", "website/pass-abi.js", "BMC_PASS_BUILD")
export("IBMCToken", "IBMCToken.sol", "website/bmc-abi.js", "BMC_TOKEN_BUILD")
print("Website ABIs match the configured Foundry build.")
